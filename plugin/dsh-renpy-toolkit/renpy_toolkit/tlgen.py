"""用引擎自己生成完整的 ``tl/<lang>/`` —— 包括「只有 .rpyc 没有 .rpy」的发行版。

为什么需要这个模块
------------------
Ren'Py 官方的 ``translate <lang>`` 命令有两个硬前提：

1. ``generation.translate_list_files()`` 只收集**磁盘上真实存在的** ``.rpy`` /
   ``.rpym`` / ``_ren.py`` 文件；
2. ``scanstrings.scan()`` 同样只扫这些文件。

商业发行版通常把脚本编译成 ``.rpyc`` 后删掉源码，于是上面两条都落空 ——
``translate Chinese`` 会「成功」退出，但只写出一个 ``common.rpym``，对白一条没有。

而引擎内存里的 ``script.translator.file_translates`` 是**齐全的**：``.rpyc`` 加载后
每个 ``Translate`` 节点都在，``identifier`` 也由引擎自己算好。缺的只是「把它们写出来」
这一步。

做法
----
在游戏目录之外放一个探针 ``.rpy``，用 ``RENPY_SEARCHPATH`` 注入到引擎的
searchpath 里，注册一个自定义命令；该命令在引擎启动完成后把内存里的翻译块按官方
``write_translates`` 的格式写进我们指定的输出目录。**全程不写游戏目录。**

.. code-block:: text

    game/            ← 只读也能工作
    scratch/probe/   ← 探针 .rpy（RENPY_SEARCHPATH 指向这里）
    scratch/src/     ← 反编译出来的 .rpy（不在 searchpath 上，只供字符串扫描）
    scratch/out/     ← 生成结果

字符串（菜单标题、``_()`` 字面量、界面文本）不在 ``file_translates`` 里，得靠词法
扫描。引擎只能扫真实文件，所以先用 :mod:`renpy_toolkit.decompile` 把 ``.rpyc``
还原到 ``scratch/src/``，再让探针对它跑 ``scanstrings.scan_strings()``。

    ``scratch/src/`` **绝不能**放进 ``RENPY_SEARCHPATH``，否则引擎会把它当成第二份
    脚本加载，重复的 label / define 会直接报错。

标识符从哪来
------------
**绝不自己算。** 引擎内存里的 ``Translate.identifier`` 就是权威值，
:func:`renpy_toolkit.fresh.identifier_for` 只用于「没有引擎可用」的降级路径。
"""

