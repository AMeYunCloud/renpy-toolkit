#: Anything that ends in one of these is a path, never a sentence.
#: The dot must be at the start or sit right after a non-space, which is what
#: separates a filename from a sentence that merely ends in an extension:
#: ``Sacred Bridge Demo.ttf`` and ``.png`` (an f-string with its field masked
#: out) qualify, while ``Save as .txt`` does not.
_ASSET_RE = re.compile(
    r"(?:(?<=\S)|^)\.(?:png|jpe?g|webp|gif|bmp|tga|svg|ogg|opus|mp3|wav|flac|m4a|"
    r"ttf|otf|ttc|rpy|rpyc|rpym|rpymc|json|txt|py|webm|mp4|avi|mkv)$",
    re.IGNORECASE,
)

#: ``#ff8800`` / ``#fff`` -- colour literals, never text.
_COLOUR_RE = re.compile(r"^#[0-9A-Fa-f]{3,8}$")

#: ``GD_tree_a`` / ``quest_wolf`` -- identifiers, never text.
_IDENT_RE = re.compile(r"^[A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)+$")

#: ``2230_04`` / ``1495_01`` -- asset frame indices, never text. Ren'Py image
#: names use the same underscore shape as identifiers, but start with digits,
#: so ``_IDENT_RE`` misses them.
_FRAME_RE = re.compile(r"^\d+(?:_\d+)+$")

#: ``0%`` / ``30`` / ``4`` -- pure numbers with no prose. The lookahead keeps
#: a bare ``%`` or ``...`` out of this bucket: those *are* translated.
_NUMERIC_RE = re.compile(r"^(?=.*\d)[\d\s.,:%+\-]+$")

#: ``b_smith_`` / ``item_`` -- a trailing underscore means a name fragment
#: used for lookup, not display text.
_TRAILING_UNDERSCORE_RE = re.compile(r"^_*\w+_+$")

#: CJK text is never junk even without ASCII letters.
_CJK_RE = re.compile(r"[\u3000-\u9fff\uff00-\uffef]")

#: Any Latin letter at all.
_LETTER_RE = re.compile(r"[A-Za-z]")

#: Byte-order marks and zero-width joiners leak in from decoded sources. They
#: are invisible, so a string made only of them can never be displayed.
_INVISIBLE_RE = re.compile("[\ufeff\u200b\u200c\u200d\u2060]")

#: A bare comment marker. Ren'Py strips ``#`` at the lexer, so this only shows
#: up when a comment line was walked as if it were code.
_COMMENT_MARKER_RE = re.compile(r"^#+$")

#: Directories that may ship developer tooling rather than player-visible content.
#: Kept for the *path* heuristic only: a literal is never dropped merely for
#: living here, because a game can ship real content in a folder that happens to
#: carry a tool-like name. What these directories do is make a ``_()``-less
#: literal suspicious, which :data:`_TOOL_DIR_WRAPPED_ONLY` encodes.
#:
#: Deliberately narrow: only names that are unambiguously tooling. ``editor`` and
#: ``tools`` are *not* here, because plenty of games use them for real content.
#: A game whose tooling lives under some other name passes it explicitly with
#: ``dev_tool_dirs=`` / ``tl gen --dev-tool-dirs NAME``; that is where
#: title-specific folder names belong, not in this default.
_DEV_TOOL_DIRS = ("devtools", "dev_tools", "debugtools")

#: Name of the module-level switch for the rule above. ``True`` means: inside a
#: dev-tool directory, accept only literals the game wrapped in ``_()``.
_TOOL_DIR_WRAPPED_ONLY = True

#: Longest plausible sentence. Anything bigger is a generated blob.
_MAX_TEXT = 4000

#: Python source inside a multi-line literal. A ``Python`` block that defines a
#: class or a function arrives at the AST walk as one literal covering the whole
#: body; that is code, and no player ever reads it.
#:
#: The patterns demand a keyword followed by a name (``def f``, ``class C``,
#: ``import os``), never a bare prefix: an earlier version matched the bare word
#: ``def`` and therefore rejected the translated line
#: ``"...more loot from \ndefeated monsters."``, whose second physical line
#: begins with ``defeated``. Assignments are deliberately not listed -- prose
#: may legitimately contain ``=``.
_CODE_BLOB_RE = re.compile(
    r"^[ \t]*(?:@\w+|(?:def|class)[ \t]+\w+|import[ \t]+\w+|from[ \t]+\w+[ \t]+import\b)",
    re.MULTILINE,
)


def _in_dev_tool_dir(rel: str, dev_tool_dirs=None) -> bool:
    """True when *rel* lives in a folder that ships developer tooling.

    Only the directory components count: a file *named* ``devtools.rpy`` at the
    top level is ordinary game content, while ``devtools/foo.rpy`` is not.

    *dev_tool_dirs* replaces the default set for this call, which is how a game
    whose tooling lives under its own folder name opts in without that name
    being baked into the default.
    """
    if not _TOOL_DIR_WRAPPED_ONLY:
        return False
    names = _DEV_TOOL_DIRS if dev_tool_dirs is None else tuple(
        str(i).lower() for i in dev_tool_dirs if str(i).strip()
    )
    return any(part.lower() in names for part in rel.replace("\\", "/").split("/")[:-1])


def looks_translatable(text: str, *, identifiers: bool = False) -> bool:
    """Conservative filter: only reject strings that provably are not prose.

    Short symbols (``+``, ``...``, ``<``, ``a``) are *kept* -- the shipped
    translations of both reference projects translate them, so dropping them
    would lose real work. Every rule below was validated against those two
    reference TL trees: none of them removes a string that either project
    actually translated.

    A path/identifier test only applies to strings with no whitespace: a real
    sentence may well embed one (``{image=bg/icons/hint.png}Go left``), and
    rejecting it would silently lose the line.

    The rules that reject *shape* rather than *content* are what keep a
    ``Python`` block's source out of the string table: a whole function body
    arrives as one literal, and so does every tag name a game declares in a
    registry (``b``, ``size``, ``color``).

    *identifiers* re-admits ``snake_case`` tokens. It exists because the rule
    that drops them is the one genuinely undecidable case: ``night_room`` may be
    a jump target and ``scene_editor`` a button label, and no syntactic test
    separates them. Dropping is right for a game whose labels dominate, and the
    reference project translates 3 such keys, so the escape hatch is real
    rather than theoretical. Callers surface it as ``--include-identifiers``.
    """
    if not isinstance(text, str):
        return False
    stripped = _INVISIBLE_RE.sub("", text).strip()
    if not stripped or len(stripped) > _MAX_TEXT:
        return False
    if _COLOUR_RE.match(stripped) or _COMMENT_MARKER_RE.match(stripped):
        return False
    if _NUMERIC_RE.match(stripped) or _FRAME_RE.match(stripped):
        return False
    if _TRAILING_UNDERSCORE_RE.match(stripped):
        return False
    # Python source, not text: a multi-line literal containing a ``def`` or an
    # import is a code block the AST walk surfaced, never a line a player reads.
    if "\n" in stripped and _CODE_BLOB_RE.search(stripped):
        return False
    has_markup = "{" in stripped or "[" in stripped
    if not has_markup and " " not in stripped and "\n" not in stripped:
        # Only the identifier rule is opt-out. A file path is never a label, so
        # ``identifiers=True`` must not let ``bg/icons/quest.png`` through.
        if not identifiers and _IDENT_RE.match(stripped):
            return False
    # A filename is never a label, with or without spaces and markup in it:
    # ``fonts/Bohemian Soul.otf`` has a space, and an f-string with its field
    # masked out reduces to ``.png``. ``_ASSET_RE`` already requires a non-space
    # before the dot, so ``Save as .txt`` (a real sentence) still survives.
    if _ASSET_RE.search(stripped):
        return False
    # A long run with neither a letter nor CJK is a glyph dump or a blob.
    if len(stripped) > 3 and not _LETTER_RE.search(stripped) \
            and not _CJK_RE.search(stripped):
        return False
    return True


def load_strings(path: str) -> list[dict]:
    """Read the probe's raw string dump."""
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    rows = payload.get("data") if isinstance(payload, dict) else payload
    return list(rows or [])


def load_fstrings(path: str) -> list[dict]:
    """Read the f-strings the probe could not turn into a ``[var]`` template.

    Each entry is ``{file, line, how, screen, text}``. They are assembled at
    runtime, so the string table can never reach them; the only fix is a source
    change (``f"..."`` -> ``_("...[name]...")`` with a ``.format`` call, or an
    explicit ``renpy.translate_string`` of the template).
    """
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    if not isinstance(payload, dict):
        return []
    return list(payload.get("fstrings") or [])


def filter_fstrings(rows: list[dict], *, dev_tool_dirs=None) -> list[dict]:
    """Drop f-strings that carry no player-visible prose.

    An f-string like ``f"{name}.png"`` is an asset path, not text; only ones
    that read like a sentence survive. ``looks_translatable`` already encodes
    that judgement for ordinary literals, so it is reused here -- but the
    ``{...}`` fields must be *removed* rather than replaced by a space: with a
    space in the middle ``f"{name}.png"`` would look like two words and slip
    through, while with the field gone it is the identifier ``.png``, which is
    exactly what the filter is meant to reject.

    *dev_tool_dirs* replaces the default developer-tooling folder set, for a
    game whose tooling lives under its own name.
    """
    kept = []
    for row in rows:
        text = str(row.get("text") or "")
        rel = str(row.get("file") or "").replace("\\", "/")
        if not rel or rel.startswith("tl/"):
            continue
        if _in_dev_tool_dir(rel, dev_tool_dirs) and not row.get("wrapped"):
            continue
        # f"..." -> the literal parts only, fields stripped out.
        masked = re.sub(r"\{[^{}]*\}", "", text)
        if masked[:1] in ("f", "F"):
            masked = masked[1:].lstrip()
        if masked[:1] in ("'", '"'):
            masked = masked[1:]
            if masked[-1:] in ("'", '"'):
                masked = masked[:-1]
        if not looks_translatable(masked):
            continue
        kept.append(row)
    kept.sort(key=lambda r: (str(r.get("file") or ""), int(r.get("line") or 0)))
    return kept


def filter_strings(rows: list[dict], *, engine: bool = False,
                   exclude: set[str] | None = None,
                   identifiers: bool = False,
                   dev_tool_dirs=None) -> list[dict]:
    """Keep player-visible rows, dropping dev tooling.

    String translation is global in Ren'Py (a single ``StringTranslator`` for
    the whole game), so one literal needs exactly one ``old`` entry no matter
    how many files mention it. Deduplication happens *here*, after dev-tool
    rows are dropped, so a literal that only appears in a developer-tooling
    folder cannot shadow the real game occurrence.

    *engine* selects which half to return: ``False`` gives the game's own
    scripts (they go to ``tl/<lang>/<script>.rpy``), ``True`` gives strings
    owned by ``renpy/common/*.rpy`` (they go to ``tl/<lang>/common.rpy`` and
    must never be mixed into the game files). Engine rows must additionally be
    ``_()``-wrapped — that is how the engine marks its own translatable
    strings, and without it the engine half is 2000+ developer-tool internals.

    *exclude* holds texts already claimed by the other half. The two halves are
    separate files but share one global string table, so a literal must live in
    exactly one of them or the engine raises
    ``A translation for "..." already exists at ...``.

    *identifiers* is forwarded to :func:`looks_translatable`; see its docstring
    for why the ``snake_case`` rule is opt-out rather than absolute.

    *dev_tool_dirs* replaces the default developer-tooling folder set; see
    :func:`_in_dev_tool_dir`.
    """
    keep_engine = bool(engine)
    excluded = exclude or set()
    kept = []
    for row in rows:
        if bool(row.get("engine")) != keep_engine:
            continue
        text = row.get("text")
        if text in excluded:
            continue
        if keep_engine and not row.get("wrapped"):
            continue
        if not looks_translatable(text, identifiers=identifiers):
            continue
        rel = str(row.get("file") or "").replace("\\", "/")
        if not rel or rel.startswith("tl/"):
            continue
        if _in_dev_tool_dir(rel, dev_tool_dirs) and not row.get("wrapped"):
            continue
        kept.append(row)
    # A literal inside a screen is reached twice: once by the dedicated screen
    # walk (which knows the owning screen) and once by the generic statement
    # walk (which does not). Sort so the context-carrying row wins, otherwise
    # the surviving row depends on file order and the plugin loses exactly the
    # information it needs to split ambiguous strings.
    kept.sort(key=lambda r: (
        str(r.get("file") or ""),
        int(r.get("line") or 0),
        str(r.get("text")),
        0 if r.get("screen") else 1,
    ))
    unique = []
    seen: set[str] = set()
    for row in kept:
        text = str(row.get("text"))
        if text in seen:
            continue
        seen.add(text)
        unique.append(row)
    return unique


def _quote(text: str) -> str:
    """Ren'Py string literal for a ``strings`` block value."""
    return '"' + format_value(text) + '"'


#: Engine-owned strings all live in this one file, as the reference project does.
ENGINE_TL_NAME = "common.rpy"


def write_string_blocks(outdir: str, language: str, rows: list[dict]) -> tuple[int, int]:
    """Append ``translate <language> strings:`` blocks to *outdir*.

    One block per string, matching the layout the reference project ships: a
    source comment directly above the header, the ``old`` / ``new`` pair
    immediately below it, and a blank line between blocks. The engine's own
    generator inserts a blank line after the header instead; both parse, but
    the reference project's shape is what the user reads, so that is what we
    emit.

    Rows flagged ``engine`` are collected into a single :data:`ENGINE_TL_NAME`
    file and anchored as ``# renpy/common/...``; the rest keep their own
    script name and a ``# game/...`` anchor.
    """
    by_file: dict[str, list[dict]] = {}
    # A string may reach us twice -- the engine scans ``renpy/common/`` and the
    # game's own scripts separately, and both can mention the same literal -- and
    # Ren'Py refuses a duplicate ``old`` in one language with
    # ``A translation for "X" already exists``.  Dedupe per target file, keeping
    # the first anchor we saw so the reported position stays meaningful.
    seen: dict[str, set[str]] = {}
    for row in rows:
        if row.get("engine"):
            rel = ENGINE_TL_NAME
        else:
            rel = str(row.get("file") or "").replace("\\", "/")
            # A row without a usable source file has nowhere to go: writing it
            # would try to create a file literally named "?".
            if not rel or rel in ("?", "None"):
                continue
        text = str(row.get("text") or "")
        bucket = seen.setdefault(rel, set())
        if text in bucket:
            continue
        bucket.add(text)
        by_file.setdefault(rel, []).append(row)

    total = 0
    for rel in sorted(by_file):
        path = os.path.join(outdir, rel)
        # ``rel`` comes from the probe's ``file`` field, i.e. from the game's
        # own script table.  It is a relative path, but nothing stops a crafted
        # or damaged script from carrying ``..`` components, and this function
        # writes whatever it is handed.  Refuse anything that resolves outside
        # the output directory instead of trusting the name.
        resolved = os.path.abspath(path)
        root = os.path.abspath(outdir)
        if os.path.commonpath([resolved, root]) != root:
            raise InvalidRequestError(
                f"refusing to write {rel!r}: it resolves outside {outdir}"
            )
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        exists = os.path.exists(path)
        chunks = []
        for row in by_file[rel]:
            source = str(row.get("file") or "").replace("\\", "/")
            if row.get("engine"):
                anchor = source
            else:
                anchor = "game/" + source
            raw = str(row.get("text") or "")
            chunks.append(
                "# {anchor}:{line}\n"
                "translate {lang} strings:\n"
                "    old {old}\n"
                "    new {old}\n".format(
                    anchor=anchor,
                    line=int(row.get("line") or 0),
                    lang=language,
                    old=_quote(raw),
                )
            )
        body = "\n".join(chunks)
        if exists:
            # The file already holds strings blocks, possibly translated by hand.
            # Appending blindly duplicates every ``old`` on a second run, and
            # Ren'Py refuses duplicates with ``A translation for "X" already
            # exists``.  Merge instead: keep what is on disk, add only the
            # literals it does not have yet.
            with open(path, "r", encoding="utf-8-sig", newline="") as handle:
                previous = handle.read()
            have = set()
            for match in re.finditer(r'^\s*old\s+"', previous, re.MULTILINE):
                tail = previous[match.end():]
                # Decode the quoted value with the TL parser's own unescaper so
                # "he said \"hi\"" compares equal to the raw AST literal.
                end = 0
                escaped = False
                while end < len(tail):
                    char = tail[end]
                    if escaped:
                        escaped = False
                    elif char == "\\":
                        escaped = True
                    elif char == '"':
                        break
                    end += 1
                have.add(unescape_value(tail[:end]))
            kept_chunks = [
                chunk for chunk, row in zip(chunks, by_file[rel])
                if str(row.get("text") or "") not in have
            ]
            # ``total`` counts what the file holds afterwards, not what this run
            # added: a second, idempotent run reports the same number as the
            # first instead of looking like it lost two thirds of the strings.
            total += len(have) + len(kept_chunks)
            if not kept_chunks:
                continue
            body = "\n".join(kept_chunks)
            with open(path, "a", encoding="utf-8", newline="\n") as handle:
                handle.write("\n")
                handle.write(body)
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            # BOM only -- see ``write_header`` in PROBE_SOURCE for why there is
            # no ``# TODO: Translation updated at ...`` timestamp here.
            handle.write("\ufeff")
            handle.write(body)
        total += len(chunks)
    return total, len(by_file)


def _restore_sources(
    game_dir: str, dest: str, failures: list[tuple[str, str]] | None = None
) -> int:
    """Decompile every ``.rpyc`` under *game_dir* into *dest*. Returns the count.

    A script that fails to decompile contributes no strings, so the failure has
    to reach the caller instead of being swallowed: silence there looks exactly
    like a game with less text.  *failures* collects ``(path, reason)``.
    """
    from .decompile import find_sources, find_scripts, decompile_file
    from .errors import ToolkitError

    # Only *dest* matters: a game that ships a few stray .rpy (options.rpy, a
    # hand-written tl file) still needs its .rpyc decompiled, and re-using an
    # earlier run's output saves a full pass.
    if find_sources(dest):
        return 0

    count = 0
    for path in find_scripts(game_dir):
        rel = os.path.relpath(path, game_dir)
        if rel.split(os.sep)[0].lower() == "tl":
            continue
        # ``rel`` comes from walking *game_dir*, but a symlinked subtree could
        # still point elsewhere; never write outside the scratch dir.
        try:
            target = safeio.safe_join(dest, os.path.splitext(rel)[0] + ".rpy",
                                      what=f"decompiled source for {rel}")
        except safeio.UnsafePathError as exc:
            if failures is not None:
                failures.append((path, str(exc)))
            continue
        os.makedirs(os.path.dirname(target), exist_ok=True)
        try:
            text, _stats = decompile_file(path)
        except (ToolkitError, OSError, ValueError) as exc:
            if failures is not None:
                failures.append((path, str(exc)))
            continue
        with open(target, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        count += 1
    return count


def generate_tl(
    basedir: str,
    language: str,
    *,
    outdir: str | None = None,
    sources: str | None = None,
    runtime: str | None = None,
    with_strings: bool = True,
    restore_sources: bool = True,
    identifiers: bool = False,
    hardcoded: bool = True,
    sections: bool = False,
    index: bool = False,
    dev_tool_dirs: tuple[str, ...] | None = None,
    clean_scratch: bool = False,
    timeout: int = 1800,
    log: list[str] | None = None,
) -> GenerateResult:
    """Run the engine probe and return what it wrote.

    *outdir* defaults to a per-project scratch directory; callers that want the
    files must pass their own directory or read :attr:`GenerateResult.outdir`.

    *sources* points at a directory of ``.rpy`` to scan for strings. When it is
    omitted and the game has no sources of its own, the ``.rpyc`` files are
    decompiled into scratch space first (``restore_sources=False`` disables it).
    The probe reads strings from the live AST, so decompiling is only a
    fallback for callers that need the sources on disk; it is not required for
    discovery and costs roughly half a minute on a 160-script project.

    *identifiers* keeps ``snake_case`` tokens that the default filter drops as
    label names. See :func:`looks_translatable`.

    *hardcoded* (default true, recommended) keeps literals that are not
    ``_()``-wrapped -- UI labels, tooltips, item names written straight into a
    ``text``/``textbutton`` and so on. The engine never looks those up, so a
    ``strings`` entry is the only way to translate them without touching the
    game; turning it off shrinks the skeleton and loses them.

    *sections* / *index* (default off) add the ``# --- <label> ---`` markers and
    the ``# === Event Index ===`` block. Both are derived from the label each
    block was compiled from -- a reading aid, not a reconstruction of the
    script -- so the files carry a note saying the source is the authority.
    They are off by default and applied after the skeleton is written.

    *dev_tool_dirs* replaces the default set of developer-tooling folder names.
    A game whose tooling lives under its own folder name passes it here rather
    than that name being baked into the default; see :func:`_in_dev_tool_dir`.

    *clean_scratch* is **not** honoured here. The scratch tree holds the
    generated files, so it can only be removed once the caller has copied them
    out; :func:`clean_scratch_tree` does that. Deleting it here would leave the
    caller with an empty ``result.outdir``.
    """
    clock = time.monotonic()
    phases: dict[str, float] = {}
    if not os.path.isdir(basedir):
        raise InvalidRequestError(f"{basedir}: not a directory")

    rt = find_runtime(basedir, explicit=runtime)
    game_dir = os.path.join(rt.root, "game")
    if not os.path.isdir(game_dir):
        raise InvalidRequestError(f"{rt.root}: 没有 game/ 目录")

    out = os.path.abspath(outdir) if outdir else ""
    scratch_base = _writable_scratch(rt, out)
    scratch = _scratch_dir(os.path.abspath(rt.root), scratch_base)
    probe_dir = os.path.join(scratch, "probe")
    src_dir = os.path.abspath(sources) if sources else os.path.join(scratch, "src")
    # ``own_out`` marks the scratch directory this function owns.  A caller's
    # ``--outdir`` may hold finished translations, so it is never cleared; the
    # scratch one is rebuilt every run, because both the probe and the string
    # writer append to files that already exist.
    own_out = not out
    if own_out:
        out = os.path.join(scratch, "out")

    # 每次重建探针目录，避免旧 .rpyc 被优先加载。
    #
    # ``scratch`` is a directory this function created (under a name it owns),
    # so clearing it is safe.  A caller's ``--outdir`` is *not*: it may point at
    # a finished translation the user wants to keep, so it is never cleared.
    if os.path.isdir(probe_dir):
        shutil.rmtree(probe_dir, ignore_errors=True)
    os.makedirs(probe_dir, exist_ok=True)
    probe_path = os.path.join(probe_dir, "rtk_gen_probe.rpy")
    with open(probe_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(build_probe_source())

    if own_out and os.path.isdir(out):
        # This run owns *out*, and both the probe and ``write_string_blocks``
        # append to a file that already exists.  Left in place, a second run
        # stacks another copy of every ``strings`` block on top of the first,
        # and Ren'Py then dies with ``A translation for "X" already exists``.
        shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out, exist_ok=True)

    result = GenerateResult(language=language, outdir=out, scratch_root=scratch)

    # Decompiling is opt-in only: the probe reads strings from the live AST
    # (``renpy.game.script``), so writing .rpy files costs about half a minute
    # on a 160-script game and changes nothing. ``restore_sources`` stays for
    # callers that want the sources on disk (reviewing a compiled-only
    # release), never as a side effect of generating a skeleton.
    if restore_sources:
        os.makedirs(src_dir, exist_ok=True)
        result.decompiled = _restore_sources(
            game_dir, src_dir, result.decompile_failures
        )

    env = dict(os.environ)
    env.update(probe_env(out, SENTINEL_LANGUAGE))
    env["RENPY_SEARCHPATH"] = probe_dir + (
        ("::" + os.environ["RENPY_SEARCHPATH"]) if os.environ.get("RENPY_SEARCHPATH") else ""
    )

    argv = rt.command(rt.root, ["rtk-gen"])
    started = time.monotonic()
    try:
        proc = subprocess.run(
            argv,
            cwd=rt.root,
            env=env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise ToolkitError(
            f"引擎生成超时（{timeout}s）：{' '.join(argv)}"
        ) from exc
    except OSError as exc:
        raise ToolkitError(f"无法启动引擎：{exc}") from exc

    result.duration = time.monotonic() - started
    phases["probe"] = result.duration
    result.stdout = (proc.stdout or "") + (proc.stderr or "")
    if log is not None:
        log.append(result.stdout)

    for line in result.stdout.splitlines():
        if line.startswith("RTK-GEN "):
            fields = dict(
                part.split("=", 1) for part in line[len("RTK-GEN "):].split() if "=" in part
            )
            result.blocks = int(fields.get("blocks", 0))
            result.strings = int(fields.get("strings", 0))

    if proc.returncode != 0 and not result.blocks:
        tail = "\n".join(result.stdout.strip().splitlines()[-25:])
        raise ToolkitError(
            f"引擎探针执行失败（exit {proc.returncode}）：\n{tail}"
        )

    _retarget_generated(out, language)
    phases["retarget"] = time.monotonic() - clock - sum(phases.values())

    raw = os.path.join(out, STRINGS_DUMP_NAME)
    if with_strings and os.path.isfile(raw):
        result.strings_json = raw
        rows = load_strings(raw)
        game_rows = filter_strings(
            rows, identifiers=identifiers, dev_tool_dirs=dev_tool_dirs)
        # A hardcoded literal is one the engine will never look up on its own;
        # a ``strings`` entry is the only way to reach it.  Counted so the run
        # report can say whether any were produced, and droppable for callers
        # that want a minimal skeleton.
        hardcoded_rows = [row for row in game_rows if not row.get("wrapped")]
        result.hardcoded_strings = len(hardcoded_rows)
        if not hardcoded:
            result.hardcoded_skipped = len(hardcoded_rows)
            result.hardcoded_strings = 0
            game_rows = [row for row in game_rows if row.get("wrapped")]
        # The engine owns one global string table, so a literal must appear in
        # exactly one file: the game half wins, and the engine half skips it.
        engine_rows = filter_strings(
            rows, engine=True, identifiers=identifiers,
            dev_tool_dirs=dev_tool_dirs,
            exclude={str(row.get("text")) for row in game_rows})
        written = write_string_blocks(
            out, language, game_rows + engine_rows
        )
        result.strings = written[0]
        result.string_files = written[1]
        # f-strings are assembled at runtime, so no strings entry can reach
        # them; surfacing the count keeps them from looking like coverage.
        result.fstring_rows = filter_fstrings(
            load_fstrings(raw), dev_tool_dirs=dev_tool_dirs)
        result.fstrings = len(result.fstring_rows)
    phases["strings"] = time.monotonic() - clock - sum(phases.values())

    for root_dir, dirs, names in os.walk(out):
        dirs.sort()
        for name in sorted(names):
            path = os.path.join(root_dir, name)
            rel = os.path.relpath(path, out).replace("\\", "/")
            if rel == STRINGS_DUMP_NAME:
                continue
            result.files.append(rel)
    result.files.sort()

    if sections or index:
        # Applied to the generated skeleton, before the caller copies it out.
        # ``backup=False``: these files were produced by this run a moment ago.
        from .sorttl import sort_tl_path

        for rel in result.files:
            if not rel.endswith(".rpy"):
                continue
            sort_tl_path(
                os.path.join(out, rel.replace("/", os.sep)),
                write_index=index,
                sections=sections,
                dry_run=False,
                backup=False,
            )
    phases["total"] = time.monotonic() - clock
    result.phases = phases

    return result


def clean_scratch_tree(scratch_root: str, *, owned: bool = True) -> bool:
    """Remove the toolkit scratch tree at *scratch_root*.

    Called by the CLI *after* the generated files have been copied out. The
    scratch tree is the one directory the toolkit appends to whatever base the
    game's interpreter could write -- which on a sandboxed launcher can be the
    game's own install directory, where 18 MB of probe output is unwelcome.

    Only a directory named ``renpy-toolkit-gen`` is ever removed, never its
    parent: with ``RTK_SCRATCH=<game>`` the parent is the user's game.

    Returns True when a directory was actually removed.
    """
    import shutil

    if not owned or not scratch_root:
        return False
    root = os.path.abspath(scratch_root)
    # ``scratch_root`` is ``<base>/renpy-toolkit-gen/<digest>``; the tree to
    # remove is the named parent, so a digest directory alone can never match.
    tree = os.path.dirname(root)
    if not scratch_is_ours(tree):
        return False
    if not os.path.isdir(tree):
        return False
    shutil.rmtree(tree, ignore_errors=True)
    return not os.path.isdir(tree)
