@dataclass
class Runtime:
    """A way to start one game's own Ren'Py runtime."""

    python: str
    """Interpreter that runs the launcher (``lib/py3-*/python.exe``)."""

    launcher: str
    """The ``<name>.py`` bootstrap next to the executable."""

    root: str
    """Directory holding the bootstrap (the project root, not ``game/``)."""

    def command(self, basedir: str, args: list[str]) -> list[str]:
        return [self.python, self.launcher, basedir, *args]

    def describe(self) -> str:
        return f"{os.path.basename(self.python)} + {os.path.basename(self.launcher)}"


def _lib_interpreters(root: str) -> list[str]:
    lib = os.path.join(root, "lib")
    if not os.path.isdir(lib):
        return []
    found = []
    try:
        names = sorted(os.listdir(lib))
    except OSError:
        return []
    for name in names:
        for exe in ("python.exe", "pythonw.exe"):
            candidate = os.path.join(lib, name, exe)
            if os.path.isfile(candidate):
                found.append(candidate)
    return found


def find_runtime(basedir: str, *, explicit: str | None = None) -> Runtime:
    """Locate the interpreter + bootstrap needed to run a wrapped distribution.

    Accepts a project root *or* a ``game/`` directory. Raises
    :class:`~renpy_toolkit.errors.ToolkitError` when nothing usable is found.

    The search covers, in order:

    1. *explicit* (either the interpreter or the ``<name>.py`` bootstrap);
    2. ``<root>/<name>.py`` + ``<root>/lib/py3-*/python.exe`` (套壳发行版);
    3. ``<root>/renpy.sh`` / ``renpy.exe`` (官方 SDK 工程);
    4. ``RENPY_SDK`` 指向的 SDK。
    """
    if not os.path.isdir(basedir):
        raise InvalidRequestError(f"{basedir}: not a directory")

    root = os.path.abspath(basedir)
    if os.path.basename(root).lower() == "game":
        root = os.path.dirname(root)

    candidates: list[str] = []
    if explicit:
        candidates.append(os.path.abspath(explicit))

    # 套壳发行版：<root>/<name>.py 与 lib/py3-*/python.exe
    interpreters = _lib_interpreters(root)
    launchers = []
    try:
        for name in sorted(os.listdir(root)):
            if name.endswith(".py") and not name.startswith("_"):
                launchers.append(os.path.join(root, name))
    except OSError:
        pass

    for launcher in launchers:
        for interp in interpreters:
            if explicit and os.path.abspath(explicit) not in (interp, launcher):
                continue
            return Runtime(python=interp, launcher=launcher, root=root)

    if explicit and os.path.isfile(explicit) and explicit.lower().endswith(".py"):
        if interpreters:
            return Runtime(python=interpreters[0], launcher=os.path.abspath(explicit), root=root)

    # 官方 SDK 工程：renpy.sh / renpy.exe 就在根目录
    for name in ("renpy.sh", "renpy.exe", "renpy"):
        candidate = os.path.join(root, name)
        if os.path.isfile(candidate):
            raise ToolkitError(
                f"{candidate} 是官方 SDK 启动器；tlgen 需要能直接调用 python 的形态。"
                "请改用 `renpy-toolkit sdk translate`，或把工程指向套壳发行版。"
            )

    env_sdk = os.environ.get("RENPY_SDK")
    if env_sdk and os.path.isdir(env_sdk):
        raise ToolkitError(
            f"只找到 SDK（{env_sdk}），没有找到游戏自带的运行时。"
            "tlgen 必须在游戏自己的 Ren'Py 版本上跑，否则标识符可能与发行版不一致。"
        )

    raise ToolkitError(
        f"{root}: 找不到 Ren'Py 运行时（既没有 lib/py3-*/python.exe，也没有 <name>.py）。"
        "用 --runtime 显式指定。"
    )


def probe_env(out: str, language: str, *, srcdir: str = "", extra: dict[str, str] | None = None) -> dict[str, str]:
    """Environment variables the probe reads."""
    env = {
        "RTK_OUT": os.path.abspath(out),
        "RTK_LANG": language,
        "RTK_SRC": os.path.abspath(srcdir) if srcdir else "",
        "PYTHONIOENCODING": "utf-8",
    }
    if extra:
        env.update(extra)
    return env


