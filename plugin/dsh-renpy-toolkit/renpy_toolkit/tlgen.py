@dataclass
class GenerateResult:
    """Outcome of one engine-side generation run."""

    language: str
    outdir: str
    files: list[str] = field(default_factory=list)
    """Relative paths written under *outdir*, sorted."""

    blocks: int = 0
    strings: int = 0
    """How many raw string rows the probe recovered."""

    string_files: int = 0
    """How many files received a ``translate <lang> strings:`` block."""

    strings_json: str = ""
    """Path to the raw probe dump (``rtk_strings.json``)."""

    fstrings: int = 0
    """How many f-strings could not be rewritten as ``[var]`` templates.

    They are assembled at runtime, so no ``strings`` entry can ever match them;
    fixing them needs a source change. ``GenerateResult.fstring_rows`` carries
    the details.
    """

    hardcoded_strings: int = 0
    """How many ``strings`` entries came from a literal that is **not**
    ``_()``-wrapped -- a hardcoded label, button caption, tooltip and so on.

    These are the texts the engine itself would never translate (nothing marks
    them), so supplying a ``strings`` entry is the only way to reach them
    without editing the game.  They are included by default; ``--no-hardcoded``
    drops them and this count becomes 0 with :attr:`hardcoded_skipped` set.
    """

    hardcoded_skipped: int = 0
    """How many hardcoded entries were dropped because ``--no-hardcoded``."""

    fstring_rows: list[dict] = field(default_factory=list)
    """``{file, line, how, screen, text}`` for each unreachable f-string."""

    stdout: str = ""
    duration: float = 0.0
    decompiled: int = 0
    """How many ``.rpyc`` had to be restored to read strings."""

    phases: dict[str, float] = field(default_factory=dict)
    """Wall-clock seconds per stage (``probe``/``retarget``/``strings``)."""

    decompile_failures: list[tuple[str, str]] = field(default_factory=list)
    """``(path, reason)`` for every ``.rpyc`` that could not be decompiled.

    Those scripts contribute no strings, so a silent failure quietly shrinks
    coverage.  Reporting them turns "coverage looks low" into a named cause.
    """

    scratch_removed: bool = False
    """True when the temporary probe tree was deleted after the run."""

    scratch_root: str = ""
    """The toolkit scratch directory this run used.

    Reported so the caller can delete it once the generated files have been
    copied out. It is *not* derivable from :attr:`outdir`: when the caller
    passes ``--outdir``, the output lives elsewhere and only the probe and
    source trees are left behind under this path.
    """

    def summary(self) -> str:
        text = (
            f"{self.language}: {self.blocks} translate block(s), "
            f"{self.strings} string(s) in {self.string_files} file(s)"
        )
        if self.hardcoded_strings:
            text += f"; 硬编码文本块 {self.hardcoded_strings} 条（已收入 strings）"
        elif self.hardcoded_skipped:
            text += f"; 硬编码文本块 0 条（按 --no-hardcoded 跳过 {self.hardcoded_skipped} 条）"
        else:
            text += "; 硬编码文本块 0 条"
        return text


#: Language key used for the probe run. Nothing is ever loaded under it, so
#: every block in memory counts as "missing" and gets written out -- which is
#: exactly what a full skeleton needs. The header is rewritten afterwards.
SENTINEL_LANGUAGE = "rtk_tmp"

#: Name of the probe's raw string dump inside the output directory. Must not
#: begin with ``__``: Ren'Py's lexer rewrites that prefix in string literals.
STRINGS_DUMP_NAME = "rtk_strings.json"


def _scratch_dir(tag: str, base: str) -> str:
    digest = hashlib.sha1(tag.encode("utf-8")).hexdigest()[:12]
    # ``base`` may already *be* a scratch root: the in-project fallback is
    # ``<game>/.renpy-toolkit-gen``. Appending unconditionally nested it a
    # second time (``.renpy-toolkit-gen/renpy-toolkit-gen``), which both looked
    # like debris and defeated cleanup, since only the inner level was removed.
    if scratch_is_ours(base):
        root = os.path.join(base, digest)
    else:
        root = os.path.join(base, "renpy-toolkit-gen", digest)
    os.makedirs(root, exist_ok=True)
    return root


def scratch_is_ours(base: str) -> bool:
    """True when *base* is a toolkit scratch root rather than a user directory.

    Used before cleaning up: the cleanup path is derived, and only a directory
    the toolkit itself created may be removed.

    Both spellings count. ``_scratch_dir`` appends ``renpy-toolkit-gen`` to the
    chosen base, while the in-project fallback base is itself
    ``.renpy-toolkit-gen``; accepting only the undotted form silently disabled
    cleanup in exactly the case that leaves debris inside a user's game.
    """
    name = os.path.basename(os.path.normpath(base))
    return name in ("renpy-toolkit-gen", ".renpy-toolkit-gen")


#: One-liner that proves the *game's* interpreter can create a file in a dir.
_WRITE_PROBE = (
    "import os,sys\n"
    "d=sys.argv[1]\n"
    "os.makedirs(d,exist_ok=True)\n"
    "p=os.path.join(d,'.rtk-write-test')\n"
    "open(p,'w').close()\n"
    "os.remove(p)\n"
    "print('OK')\n"
)


def scratch_candidates(rt: "Runtime", outdir: str | None) -> list[str]:
    """Ordered bases the scratch tree may be built under, best first.

    Split out from :func:`_writable_scratch` so the ordering is testable without
    launching an interpreter.

    ``os.getcwd()`` is deliberately the last resort rather than an early one.
    A bundled interpreter that cannot write ``%TEMP%`` reports the *current
    directory* as its temp directory, so a scratch tree built on ``getcwd()``
    lands inside whatever tree the caller happens to be standing in — for this
    plugin that was the package's own install directory, which is how 18 MB of
    a third party's dialogue ended up next to our source.
    """
    return [
        os.environ.get("RTK_SCRATCH") or "",
        os.path.dirname(os.path.abspath(outdir)) if outdir else "",
        tempfile.gettempdir(),
        os.path.join(os.path.expanduser("~"), ".renpy-toolkit"),
        # The game's install root is the one directory the launcher is
        # guaranteed to be able to write, since it ships with the game. It sits
        # after the temp options because scratch left there is debris in
        # something the user owns; the caller cleans it up (see
        # ``scratch_is_ours``).
        os.path.join(rt.root, ".renpy-toolkit-gen"),
        # Absolutely last: only reachable when every directory above failed.
        os.getcwd(),
    ]


def _writable_scratch(rt: "Runtime", outdir: str | None) -> str:
    """Pick a scratch base the *game's* interpreter can actually write to.

    The launcher's python is frequently more restricted than the caller's (it
    may be a bundled build with a different temp directory, or run under a
    sandbox), so ``tempfile.gettempdir()`` on our side proves nothing. Ask the
    runtime itself, cheapest candidate first; see
    :func:`scratch_candidates` for the order and why it matters.
    """
    candidates = scratch_candidates(rt, outdir)
    seen: set[str] = set()
    for base in candidates:
        if not base:
            continue
        base = os.path.abspath(base)
        if base in seen:
            continue
        seen.add(base)
        try:
            proc = subprocess.run(
                [rt.python, "-c", _WRITE_PROBE, base],
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=60,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if proc.returncode == 0 and "OK" in (proc.stdout or ""):
            return base
    raise ToolkitError(
        "找不到游戏运行时可写的临时目录；用环境变量 RTK_SCRATCH 指定一个。"
    )


def _retarget_generated(out: str, language: str) -> None:
    """Rewrite ``translate rtk_tmp ...`` headers to the real *language*."""
    needle = f"translate {SENTINEL_LANGUAGE} "
    for dirpath, dirnames, names in os.walk(out):
        dirnames.sort()
        for name in sorted(names):
            if not name.endswith((".rpy", ".rpym")):
                continue
            path = os.path.join(dirpath, name)
            with open(path, "r", encoding="utf-8-sig", newline="") as handle:
                text = handle.read()
            if needle not in text:
                continue
            text = text.replace(needle, f"translate {language} ")
            with open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write("\ufeff" + text)


