"""Ren'Py 工程脚手架生成（「游戏制作」一侧）。

Ren'Py 官方的创建方式是启动 launcher/gui：选项目目录、填项目名、选分辨率。
插件在无 GUI 的机器上（CI、翻译工位、服务器）复刻这件事：按 Ren'Py 8 的约定
落盘一个**能直接 `renpy.sh <dir>` 跑起来**的最小工程。

设计取舍：

- 只生成 Ren'Py 官方 `gui init` 之后的等价结构，不试图替代 SDK。生成后你
  仍要 `python -m renpy_toolkit sdk-compile` 或直接交给 launcher 打包。
- 模板是完整可用的最小集，不是占位片段。`options.rpy` 只写必须改的项，
  其余交给引擎默认值 —— 这样升级 SDK 时不会因为我们钉死了默认值而失效。
- `gui.rpy` 用 Ren'Py 官方的 `gui.init()` 再覆盖少量变量；比完整抄一份
  500 行 gui.rpy 更抗版本变化。
- 所有文件写 UTF-8、LF 结尾，与 Ren'Py 源码仓库一致。

注：本模块只写文件、不执行任何东西，因此在本机无法运行 renpy 时也能用。
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from typing import Mapping

from .errors import ToolkitError, ScaffoldError

SLUG_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")

#: 分辨率预设（宽 x 高），与 launcher 的常用项一致。
RESOLUTIONS: dict[str, tuple[int, int]] = {
    "1920x1080": (1920, 1080),
    "1600x900": (1600, 900),
    "1280x720": (1280, 720),
    "2560x1440": (2560, 1440),
}

BASE_FONT = "DejaVuSans.ttf"


class _Template:
    """One generated file."""

    def __init__(self, path: str, content: str, executable: bool = False) -> None:
        self.path = path
        self.content = content
        self.executable = executable


@dataclass
class ScaffoldResult:
    root: str
    files: list[str]
    created: bool

    def summary(self) -> str:
        verb = "created" if self.created else "refreshed"
        lines = [f"{self.root}: {verb} with {len(self.files)} files"]
        lines.extend(f"  {p}" for p in self.files)
        return "\n".join(lines)


def _quote(text: str) -> str:
    """Escape for a Ren'Py double-quoted string (mirrors encode_say_string)."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _options_rpy(vars_: Mapping[str, object]) -> str:
    out: list[str] = [
        "## 生成工具：renpy_toolkit.scaffold",
        "## 这里只写必须显式声明的项；其余用引擎默认值。",
        "",
        "init python:",
        "",
    ]
    for key, value in vars_.items():
        if value is None:
            rendered = "None"
        elif isinstance(value, bool):
            rendered = "True" if value else "False"
        elif isinstance(value, int):
            rendered = str(value)
        else:
            rendered = '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'
        out.append(f"    config.{key} = {rendered}")
    out.append("")
    return "\n".join(out)


def _gui_rpy(width: int, height: int, scale: float, font_size: int) -> str:
    return (
        "## 生成工具：renpy_toolkit.scaffold\n"
        "## 用官方 gui.init() 再覆盖少量变量，避免与 SDK 默认值脱节。\n"
        "\n"
        "init python:\n"
        "    gui.init(1920, 1080)\n"
        "\n"
        f"    gui.text_size = {font_size}\n"
        f"    gui.name_text_size = {font_size + 2}\n"
        f"    gui.interface_text_size = {max(12, font_size - 4)}\n"
        '    gui.text_font = "gui_font"          # 在 gui.rpy 里定义\n'
        "\n"
        "    ## 中文字体请在字体文件就位后改这里，例如：\n"
        '    ##   gui.text_font = "SourceHanSansSC-Regular.otf"\n'
        "    ## 文件名必须纯 ASCII，缺字检测见 toolkit.fonts。\n"
        "\n"
        "    ## 中文/多语言常用项：声明式界面样式。没有它，切换语言时旧语言的\n"
        "    ## 字体会残留在推断样式的界面元素上。\n"
        "    config.declarative_config_variables = True\n"
        "\n"
        f"    ## 设计分辨率 {width}x{height}，全局缩放 {scale:.2f}。\n"
        f"    config.screen_width = {width}\n"
        f"    config.screen_height = {height}\n"
        "\n"
    )


def _script_rpy(title: str) -> str:
    safe = _quote(title)
    return (
        f"## {safe} — 由 renpy_toolkit.scaffold 生成的起始脚本。\n"
        "\n"
        "# 自定义角色：定义后 say 语句可写 `e \"...\"`（会进翻译标识符）。\n"
        "define e = Character(_(\"Eileen\"), who_color=\"#c8ffc8\")\n"
        "\n"
        "label start:\n"
        "\n"
        "    scene black\n"
        "\n"
        '    "Ready to start."\n'
        "\n"
        "    menu:\n"
        "\n"
        '        "Begin":\n'
        "            jump begin\n"
        "\n"
        '        "Load":\n'
        "            jump begin\n"
        "\n"
        '        "Preferences":\n'
        "            jump begin\n"
        "\n"
        "label begin:\n"
        "\n"
        '    e "Hello, world."\n'
        "\n"
        "    return\n"
        "\n"
    )


def _common_tl(language: str) -> str:
    """Placeholder strings block.

    The ``old`` values match the strings ``script.rpy`` actually contains, so
    the generated file is lint-clean from the start. Everything else is meant
    to be regenerated by ``sdk translate``.

    **Each ``new`` repeats its source text on purpose.** An empty ``new`` does
    not mean "not translated yet" at runtime — ``StringTranslator.translate()``
    does ``new = self.translations.get(old, None)`` and then
    ``if new is not None: return new``, so ``""`` is a hit and the label renders
    blank. Keeping the source text means a half-finished translation stays
    playable, and ``tl verify`` still reports each untranslated entry as
    ``UNTRANSLATED`` because source and target are identical.
    """
    pairs = (
        ("Start", "Start"),
        ("Load", "Load"),
        ("Preferences", "Preferences"),
        ("Ready to start.", "Ready to start."),
        ("Hello, world.", "Hello, world."),
    )
    body = "".join(
        f'    old "{old}"\n    new "{new}"\n\n' for old, new in pairs
    )
    return (
        f"# game/tl/{language}/ — 由 renpy_toolkit.scaffold 生成。\n"
        "# 用 `renpy <project> translate " + language + "` 填充 blocks；\n"
        "# 界面字符串用 `extract_strings` / `merge_strings` 走 JSON。\n"
        "#\n"
        "# new 先照抄 old：空 new 不是「未翻译」，运行时会显示为空白。\n"
        "\n"
        f"translate {language} strings:\n"
        "\n"
        + body
    )


def new_project(
    name: str,
    dest: str | None = None,
    *,
    resolution: str = "1920x1080",
    language: str = "chinese",
    author: str = "",
    version: str = "1.0",
    overwrite: bool = False,
) -> ScaffoldResult:
    """Create a minimal but runnable Ren'Py 8 project.

    Parameters
    ----------
    name:
        Human readable project name. Used verbatim in ``config.name``.
    dest:
        Parent directory. The project is created at ``<dest>/<slug>/``.
        ``None`` means the current directory, i.e. ``./<slug>``. Following the
        launcher's own convention, everything Ren'Py reads lives under
        ``<slug>/game/``.
    resolution:
        Key of :data:`RESOLUTIONS`.
    language:
        Initial translation to scaffold. ``""`` skips the ``tl/`` tree.
    overwrite:
        Allow writing into a non-empty directory. Existing files are **still**
        never clobbered — a collision raises, so this only tolerates unrelated
        neighbours (e.g. ``.git/``).
    """
    if not name or not name.strip():
        raise ScaffoldError("project name must not be empty")
    # `name` is the project *title*, not a path. Handing a path to it is a
    # common mistake (`project new E:\work\MyGame`), and silently flattening
    # it into `./e-work-my-game` creates a directory nobody looks at. Reject
    # anything shaped like a path and point at the right arguments instead.
    if os.sep in name or (os.altsep and os.altsep in name) or os.path.isabs(name):
        raise ScaffoldError(
            f"{name!r} looks like a path, not a project name. Pass the bare "
            "name (it becomes <dest>/<slug>/), e.g. "
            "`project new MyGame --dest /path/to/parent`"
        )
    slug = re.sub(r"[^A-Za-z0-9]+", "-", name.strip()).strip("-").lower()
    if not slug:
        raise ScaffoldError(f"cannot derive a directory name from {name!r}")
    if resolution not in RESOLUTIONS:
        raise ScaffoldError(
            f"unknown resolution {resolution!r}; pick from {sorted(RESOLUTIONS)}"
        )
    if language and not SLUG_RE.match(language.replace("-", "_")):
        raise ScaffoldError(
            f"language {language!r} must be [A-Za-z][A-Za-z0-9_]* "
            "(Ren'Py 语言目录名要求纯 ASCII)"
        )

    root = os.path.abspath(os.path.join(dest if dest is not None else ".", slug))
    if os.path.exists(root) and os.listdir(root) and not overwrite:
        raise ScaffoldError(
            f"{root} exists and is not empty; pass overwrite=True to continue"
        )

    width, height = RESOLUTIONS[resolution]
    scale = 1080.0 / max(width, height)
    font_size = 26 if height >= 1080 else 22
    # Leaving default_language as None lets Ren'Py fall through its own chain
    # (RENPY_LANGUAGE -> config.language -> remembered choice -> autodetect).
    language_default = None if language else "english"

    options = _options_rpy(
        {
            "name": name.strip(),
            "version": version,
            "author": author,
            "screen_width": width,
            "screen_height": height,
            "thumbnail_width": width,
            "thumbnail_height": height,
            "default_language": language_default,
        }
    )

    files: list[_Template] = [
        _Template("game/options.rpy", options),
        _Template("game/gui.rpy", _gui_rpy(width, height, scale, font_size)),
        _Template("game/script.rpy", _script_rpy(name.strip())),
    ]
    if language:
        files.append(
            _Template(f"game/tl/{language}/common.rpy", _common_tl(language))
        )

    written: list[str] = []
    for item in files:
        target = os.path.join(root, item.path)
        if os.path.exists(target):
            raise ScaffoldError(f"refusing to clobber existing {target}")
        os.makedirs(os.path.dirname(target) or root, exist_ok=True)
        data = item.content.replace("\r\n", "\n")
        with open(target, "wb") as fh:
            fh.write(data.encode("utf-8"))
        written.append(item.path)
        if item.executable:  # pragma: no cover - no templates are executable yet
            os.chmod(target, 0o755)

    return ScaffoldResult(root=root, files=written, created=True)


def tl_skeleton(
    project_dir: str,
    language: str,
    *,
    with_common: bool = True,
) -> list[str]:
    """Create ``tl/<language>/`` in an existing project.

    Intentionally tiny: the real blocks come from ``sdk translate``. This only
    guarantees the directory, a ``common.rpy`` placeholder, and that the
    language name is ASCII (font and file-system safety, see toolkit.fonts).
    """
    if not language:
        raise ToolkitError("language must be non-empty")
    if not SLUG_RE.match(language.replace("-", "_")):
        raise ScaffoldError(f"language {language!r} must be [A-Za-z][A-Za-z0-9_]*")
    if not os.path.isdir(project_dir):
        raise ToolkitError(f"{project_dir} is not a directory")
    tl_dir = os.path.join(project_dir, "tl", language)
    os.makedirs(tl_dir, exist_ok=True)
    out: list[str] = []
    if with_common:
        target = os.path.join(tl_dir, "common.rpy")
        if not os.path.exists(target):
            with open(target, "wb") as fh:
                fh.write(
                    _common_tl(language).replace("\r\n", "\n").encode("utf-8")
                )
            out.append(target)
    return out


def verify_project(project_dir: str) -> list[str]:
    """Return a list of problems with a generated project (empty = good).

    Only checks the scaffold's own invariants; a real project needs
    ``renpy <dir> lint`` for full coverage (see toolkit.sdk).

    Layout expectation: everything lives under ``<project_dir>/game/``. A file
    sitting at the project root would be invisible to Ren'Py (it only reads
    ``game/``), so that is reported as a problem rather than accepted.
    """
    problems: list[str] = []
    game = os.path.join(project_dir, "game")
    if not os.path.isdir(game):
        problems.append(f"missing game/ directory in {project_dir}")
    required = ["options.rpy", "script.rpy"]
    for rel in required:
        if not os.path.exists(os.path.join(game, rel)):
            problems.append(f"missing {rel}")
    for dirpath, _dirnames, filenames in os.walk(project_dir):
        for filename in filenames:
            if not filename.isascii():
                problems.append(
                    f"non-ASCII filename: {os.path.join(dirpath, filename)}"
                    " — Ren'Py 与安卓 loader 对非 ASCII 文件名不可靠"
                )
    return problems


