"""Measure a candidate filter rule against a finished translation, before shipping it.

Every filter in ``tlgen.looks_translatable`` exists because a real string was
being wrongly kept or wrongly dropped. Those rules were chosen by counting, not
by taste: this script prints, for a given TL directory, how many already
translated strings a candidate rule would delete. A rule that deletes a string
somebody bothered to translate is a bug.

Usage::

    python tools/check_filter.py <tl-dir>
    python tools/check_filter.py <tl-dir> --show 40

Any TL directory works — one generated by ``tl gen``, or a finished translation.
No corpus ships with this repository, so the path is required.
"""
from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "plugin", "dsh-renpy-toolkit"))

from renpy_toolkit import tl, tlgen  # noqa: E402

# Candidate rule: the whole literal is nothing but text tags, so it has no
# visible text to translate.
_TAGS_ONLY_RE = re.compile(r"^(?:\{[^{}]*\}|\s)+$")

# Candidate rule: a single whole tag, e.g. "{s}" or "{/s}".
_ONE_TAG_RE = re.compile(r"^\{/?[A-Za-z][^{}]*\}$")


def collect(tl_dir: str) -> set[str]:
    """Every ``old``/say text that the given TL directory has a translation for."""
    found: set[str] = set()
    for dirpath, _dirnames, filenames in os.walk(tl_dir):
        for name in sorted(filenames):
            if not name.endswith((".rpy", ".rpym")):
                continue
            doc = tl.parse_tl_file(os.path.join(dirpath, name))
            for block in doc.blocks:
                for pair in getattr(block, "strings", ()):
                    if pair.old:
                        found.add(pair.old)
                for line in getattr(block, "say_lines", ()):
                    text = getattr(line, "text", None)
                    if text:
                        found.add(text)
    return found


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__.strip())
        return 2

    tl_dir = argv[0]
    show = 25
    if "--show" in argv:
        try:
            show = int(argv[argv.index("--show") + 1])
        except (IndexError, ValueError):
            print("--show needs a number")
            return 2

    if not os.path.isdir(tl_dir):
        print("not a directory: %s" % (tl_dir,))
        return 2

    olds = collect(tl_dir)
    if not olds:
        print("no translated strings found under %s" % (tl_dir,))
        return 1

    print("unique translated strings: %d" % (len(olds),))
    kept = [s for s in olds if tlgen.looks_translatable(s)]
    print("currently kept: %d, currently dropped: %d" % (len(kept), len(olds) - len(kept)))

    candidates = [
        ("asset path with spaces", lambda s: bool(tlgen._ASSET_RE.search(s))),
        ("tags-only literal", lambda s: bool(_TAGS_ONLY_RE.match(s))),
        ("single whole tag", lambda s: bool(_ONE_TAG_RE.match(s))),
    ]
    for label, test in candidates:
        hits = sorted(s for s in kept if test(s))
        print("\n[candidate] %s -- would drop %d" % (label, len(hits)))
        for one in hits[:show]:
            print("   %r" % (one,))
        if len(hits) > show:
            print("   ... and %d more" % (len(hits) - show,))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
